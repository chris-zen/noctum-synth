#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn rev2_special_values_are_exact_and_normalized() {
        assert_eq!(GatedStep::from_rev2_raw(125), GatedStep::Value(125));
        assert_eq!(GatedStep::from_rev2_raw(126), GatedStep::Reset);
        assert_eq!(GatedStep::from_rev2_raw(127), GatedStep::Rest);
        assert_eq!(GatedStep::from_rev2_raw(u16::MAX), GatedStep::Rest);
        assert_eq!(PolyNote::from_rev2_raw(127), PolyNote::Note(127));
        assert_eq!(PolyNote::from_rev2_raw(128), PolyNote::Tie);
        assert_eq!(PolyNote::from_rev2_raw(u16::MAX), PolyNote::Tie);
        assert_eq!(PolyVelocity::from_rev2_raw(0), PolyVelocity::Reset);
        assert_eq!(PolyVelocity::from_rev2_raw(127), PolyVelocity::Reset);
        assert_eq!(PolyVelocity::from_rev2_raw(128), PolyVelocity::Rest);
        assert_eq!(PolyVelocity::from_rev2_raw(129), PolyVelocity::Velocity(1));
        assert_eq!(
            PolyVelocity::from_rev2_raw(255),
            PolyVelocity::Velocity(127)
        );
    }

    #[test]
    fn invalid_edit_addresses_do_not_mutate_sequence() {
        let mut sequence = LayerSequence::default();
        let expected = sequence;
        sequence.apply(SequenceUpdate::GatedStep {
            track: u8::MAX,
            step: u8::MAX,
            value: GatedStep::Rest,
        });
        sequence.apply(SequenceUpdate::PolyNote {
            step: u8::MAX,
            lane: u8::MAX,
            value: PolyNote::Tie,
        });
        sequence.apply(SequenceUpdate::PolyLaneStep {
            step: u8::MAX,
            lane: u8::MAX,
            value: PolyLaneStep {
                note: PolyNote::Tie,
                velocity: PolyVelocity::Velocity(127),
            },
        });
        assert_eq!(sequence, expected);
    }

    #[test]
    fn whole_poly_lane_update_applies_note_and_velocity_together() {
        let mut sequence = LayerSequence::default();
        let value = PolyLaneStep {
            note: PolyNote::Tie,
            velocity: PolyVelocity::Velocity(127),
        };
        sequence.apply(SequenceUpdate::PolyLaneStep {
            step: 12,
            lane: 4,
            value,
        });
        assert_eq!(sequence.poly.steps[12].lanes[4], value);
    }

    #[test]
    fn validation_clamps_directly_constructed_payload_values() {
        let mut sequence = LayerSequence::default();
        sequence.gated.tracks[0].destination = GatedDestination::Modulation(ModDestination::Off);
        sequence.gated.tracks[0].steps[0] = GatedStep::Value(u8::MAX);
        sequence.poly.steps[0].lanes[0] = PolyLaneStep {
            note: PolyNote::Note(u8::MAX),
            velocity: PolyVelocity::Velocity(0),
        };
        sequence.validate();
        assert_eq!(sequence.gated.tracks[0].destination, GatedDestination::Off);
        assert_eq!(sequence.gated.tracks[0].steps[0], GatedStep::Value(125));
        assert_eq!(sequence.poly.steps[0].lanes[0].note, PolyNote::Note(127));
        assert_eq!(
            sequence.poly.steps[0].lanes[0].velocity,
            PolyVelocity::Velocity(1)
        );
    }

    #[cfg(feature = "serde")]
    #[test]
    fn serde_requires_exactly_sixty_four_poly_steps() {
        let sequence = PolySequence::default();
        let json = serde_json::to_string(&sequence).unwrap();
        assert_eq!(
            serde_json::from_str::<PolySequence>(&json).unwrap(),
            sequence
        );
        let mut short = serde_json::to_value(sequence).unwrap();
        short.as_array_mut().unwrap().pop();
        assert!(serde_json::from_value::<PolySequence>(short).is_err());
    }
}
